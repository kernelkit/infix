"""PPP for bearers where ModemManager reports IP method 'ppp'.

AT-only modems carry data as PPP over the same tty ModemManager dialed
on.  modemd runs pppd on it, naming the link after the configured wwan
interface.  Route and DNS servers are handled by the system's ip-up and
ip-down scripts, shared with PPPoE, which read the env file written here.
"""
import subprocess

from . import fwrite, rmf, runcmdj, stopproc

ENVFILE = "/etc/default/pppd-%s"


def start(tty, ifname, bearer):
    """Start pppd on tty, the link is named ifname.  Returns the process."""
    fwrite(ENVFILE % ifname,
           "# Generated by modemd, read by /etc/ppp/ip-up\n"
           "DEFAULT_ROUTE=1\n"
           "ROUTE_PREFERENCE=%s\n" % bearer.get("route-preference", 200))

    cmd = ["pppd", "/dev/%s" % tty, "nodetach", "ifname", ifname,
           "noauth", "noipdefault", "nodefaultroute", "usepeerdns",
           "lcp-echo-interval", "10", "lcp-echo-failure", "3"]
    cmd.append("noipv6" if bearer.get("ip-type") == "ipv4" else "+ipv6")
    if bearer.get("username"):
        cmd += ["user", bearer["username"],
                "password", bearer.get("password", ""), "hide-password"]

    return subprocess.Popen(cmd)


def stop(proc, ifname):
    """Stop pppd, its ip-down script drops the route and DNS servers."""
    stopproc(proc)
    rmf(ENVFILE % ifname)


def is_up(ifname):
    """True once the PPP link has an IPv4 address."""
    links = runcmdj(["ip", "-j", "-4", "addr", "show", "dev", ifname]) or []
    return any(link.get("addr_info") for link in links)


def is_placeholder(ifname):
    """True if ifname is confd's dummy placeholder for a missing modem."""
    links = runcmdj(["ip", "-j", "-d", "link", "show", "dev", ifname]) or []
    return any(link.get("linkinfo", {}).get("info_kind") == "dummy"
               for link in links)
